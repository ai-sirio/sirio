/// The plugin template. Only `__SIRIOCTL__` is replaced by [`prepare`]; the
/// braces in the JS template literal are left untouched (no `format!`
/// interpolation). The pane is read from the `SIRIO_PANE_ID` of the opencode
/// process that loads the plugin, never written into the file: one worktree
/// holds one plugin file for all of its OpenCode tabs, so a pane named there
/// would be every tab's (the last one prepared). Outside a Sirio pane there is
/// none, and the plugin reports nothing.
const PLUGIN_TEMPLATE: &str = "// Generated by Sirio — reports the OpenCode session id for restore.
export const SirioSession = async ({ $ }) => {
  let reported = \"\"
  const sirioctl = __SIRIOCTL__
  const pane = process.env.SIRIO_PANE_ID ?? \"\"
  return {
    event: async ({ event }) => {
      const id = event?.properties?.info?.id
      if (event?.type === \"session.updated\" && pane && id && id !== reported) {
        reported = id
        await $`${sirioctl} session-ref --session ${pane} --ref ${id}`.quiet().nothrow()
      }
    },
  }
}
";

/// The user-global variant of [`PLUGIN_TEMPLATE`], in OpenCode 1.x's plugin
/// shape (OpenCode 2 refuses it): one file serves every pane, so it names none — sirioctl resolves the pane from the
/// `SIRIO_PANE_ID` opencode inherited, and stays silent outside a Sirio
/// pane. Only `__SIRIOCTL__` is replaced.
const GLOBAL_PLUGIN_TEMPLATE: &str =
    "// Generated by Sirio — reports the OpenCode session id for restore.
// Installed user-globally from Sirio's Settings; the pane comes from the
// SIRIO_PANE_ID a Sirio terminal exports, so outside one this is inert.
export const SirioSession = async ({ $ }) => {
  let reported = \"\"
  const sirioctl = __SIRIOCTL__
  return {
    event: async ({ event }) => {
      const id = event?.properties?.info?.id
      if (event?.type === \"session.updated\" && id && id !== reported) {
        reported = id
        await $`${sirioctl} session-ref --ref ${id}`.quiet().nothrow()
      }
    },
  }
}
";

/// What the process knows of the installed OpenCode's major version.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InstalledMajor {
    /// Nothing has asked the binary yet.
    NotProbed,
    /// The binary was asked and gave no version (missing, slow, unparsable).
    Unknown,
    /// The binary's own major version.
    Major(u64),
}

/// The memo behind [`note_installed_major`]: `u64::MAX` is "not probed", `u64::MAX - 1` is
/// "unknown", anything else is a major version.
static INSTALLED_MAJOR: AtomicU64 = AtomicU64::new(u64::MAX);
const UNKNOWN_MAJOR: u64 = u64::MAX - 1;

/// Records what a probe of `opencode --version` found (`None`: no answer). Process-wide: the
/// plugin step (`prepare`, Install Hooks) runs on threads that must not exec the binary. A
/// version, once known, is not unlearnt: a later probe with no answer (slow, failed) is no news
/// and leaves it.
pub fn note_installed_major(major: Option<u64>) {
    match major {
        Some(major) if major < UNKNOWN_MAJOR => INSTALLED_MAJOR.store(major, Ordering::Relaxed),
        _ => {
            let _ = INSTALLED_MAJOR.fetch_update(Ordering::Relaxed, Ordering::Relaxed, |current| {
                (current >= UNKNOWN_MAJOR).then_some(UNKNOWN_MAJOR)
            });
        }
    }
}

/// The memo [`note_installed_major`] keeps.
pub fn installed_major_state() -> InstalledMajor {
    match INSTALLED_MAJOR.load(Ordering::Relaxed) {
        u64::MAX => InstalledMajor::NotProbed,
        UNKNOWN_MAJOR => InstalledMajor::Unknown,
        major => InstalledMajor::Major(major),
    }
}

/// The major version in what `opencode --version` printed: the first token that starts with
/// digits after an optional `v` (`opencode v2.3.0`, `1.18.33`).
pub fn parse_version_major(output: &str) -> Option<u64> {
    output.split_whitespace().find_map(|token| {
        let token = token.strip_prefix('v').unwrap_or(token);
        let digits: String = token.chars().take_while(char::is_ascii_digit).collect();
        let rest = &token[digits.len()..];
        if digits.is_empty() || !(rest.is_empty() || rest.starts_with('.')) {
            return None;
        }
        digits.parse().ok()
    })
}

/// What [`OpenCodeAdapter`]'s `prepare` does, with the version state given instead of the
/// memo's: the skill, then [`prepare_plugin`] for `state`. For a caller that has just probed
/// the binary itself and must decide on that answer.
pub fn prepare_with(
    worktree_path: &str,
    pane_id: &str,
    sirioctl_path: &str,
    state: InstalledMajor,
) -> Result<(), PrepareError> {
    use crate::AgentAdapter;
    if let Some(markdown) = OpenCodeAdapter.skill_markdown() {
        crate::install_skill(markdown, OpenCodeAdapter.id(), worktree_path)?;
    }
    prepare_plugin(worktree_path, pane_id, sirioctl_path, state)
}

/// The worktree-local plugin step of [`prepare`](super::AgentAdapter::prepare), by what is
/// known of the installed OpenCode. The plugin is written only for a confirmed OpenCode 1.x:
/// OpenCode 2 refuses it (and Sirio creates its sessions, so none is needed), and a binary that
/// gave no version may well be a 2 whose probe failed, where the plugin brings back "Plugin
/// failed". Under 2 or an unknown version nothing is written and Sirio's own generated file, if
/// one is there (the current text or the legacy one that names a pane), is removed. The pane is
/// never written into the 1.x plugin, which reads it from the environment, so `_pane_id` is
/// unused. Not probed
/// yet: nothing happens, the caller runs this again once the probe answers.
pub fn prepare_plugin(
    worktree_path: &str,
    _pane_id: &str,
    sirioctl_path: &str,
    state: InstalledMajor,
) -> Result<(), PrepareError> {
    const RELATIVE: &str = ".opencode/plugin/sirio-session.js";
    match state {
        InstalledMajor::NotProbed => Ok(()),
        InstalledMajor::Major(major) if major < 2 => {
            let plugin = PLUGIN_TEMPLATE.replace("__SIRIOCTL__", &json_string_literal(sirioctl_path));
            write_in_worktree(Path::new(worktree_path), Path::new(RELATIVE), plugin.as_bytes())?;
            Ok(())
        }
        InstalledMajor::Major(_) | InstalledMajor::Unknown => {
            remove_in_worktree_if(Path::new(worktree_path), Path::new(RELATIVE), |text| {
                is_generated(text, PLUGIN_TEMPLATE)
                    || is_generated(text, LEGACY_PANE_PLUGIN_TEMPLATE)
            })?;
            Ok(())
        }
    }
}

/// The command line of a fresh OpenCode tab: `opencode`, resuming `session_ref` when Sirio
/// created that session, with `prompt` as the first message when it is not empty.
pub fn launch_command(session_ref: Option<&str>, prompt: &str) -> String {
    let mut command = String::from("opencode");
    if let Some(reference) = session_ref {
        command.push_str(" --session ");
        command.push_str(&shell_quote(reference));
    }
    if !prompt.is_empty() {
        command.push_str(" --prompt ");
        command.push_str(&prompt_argument(prompt));
    }
    command
}

/// OpenCode has no lifecycle hook mechanism for status: OpenCode 2's is read
/// from its service (`sirio_opencode_watch`). For a confirmed OpenCode 1.x `prepare` writes
/// a worktree-local plugin (never global config) whose only job is reporting
/// the session id via `sirioctl session-ref`; OpenCode 2 refuses that plugin,
/// so under it, and under a version that could not be read, none is written and the app
/// creates the session itself (`launch_command` with the id), see [`prepare_plugin`].
pub struct OpenCodeAdapter;

impl super::AgentAdapter for OpenCodeAdapter {
    fn id(&self) -> &'static str {
        "opencode"
    }

    fn display_name(&self) -> &'static str {
        "OpenCode"
    }

    fn has_native_hooks(&self) -> bool {
        false
    }

    fn skill_markdown(&self) -> Option<&'static str> {
        // F-AGENT-SAFE-01: see `ClaudeCodeAdapter::skill_markdown`.
        Some(include_str!("../../../../skills/sirio/SKILL.md"))
    }

    fn prepare(
        &self,
        worktree_path: &str,
        pane_id: &str,
        sirioctl_path: &str,
    ) -> Result<(), PrepareError> {
        prepare_with(worktree_path, pane_id, sirioctl_path, installed_major_state())
    }

    fn install_global_hooks(
        &self,
        home: &Path,
        environment: &BTreeMap<String, String>,
        sirioctl_path: &str,
    ) -> Result<GlobalHookInstall, PrepareError> {
        let dir = opencode_config_dir(home, environment).join("plugins");
        let path = dir.join(GLOBAL_PLUGIN_FILE);
        // The global v1 plugin is written only for a confirmed OpenCode 1.x. OpenCode 2 refuses
        // it and Sirio creates its sessions; a binary that gave no version may be a 2 whose
        // probe failed. Either way nothing is written and Sirio's own generated file is removed
        // (a file that is not exactly the generated text is the user's). The version is the
        // binary's own `--version` (`note_installed_major`), not the service registration, which
        // can outlive a return to 1.x.
        match installed_major_state() {
            InstalledMajor::Major(major) if major < 2 => {}
            InstalledMajor::Major(_) => {
                return Ok(GlobalHookInstall::NotNeeded {
                    reason: "OpenCode 2 needs none: Sirio creates its sessions",
                    removed: remove_generated_global(&path)?.then_some(path),
                });
            }
            InstalledMajor::Unknown | InstalledMajor::NotProbed => {
                return Ok(GlobalHookInstall::NotNeeded {
                    reason: "OpenCode did not report its version, so no plugin was written",
                    removed: remove_generated_global(&path)?.then_some(path),
                });
            }
        }
        std::fs::create_dir_all(&dir)?;

        let plugin =
            GLOBAL_PLUGIN_TEMPLATE.replace("__SIRIOCTL__", &json_string_literal(sirioctl_path));
        std::fs::write(&path, plugin)?;
        Ok(GlobalHookInstall::Written(path))
    }

    fn command(&self, _worktree_path: &str, _pane_id: &str, _sirioctl_path: &str) -> String {
        "opencode".to_string()
    }

    fn command_with_prompt(&self, worktree_path: &str, pane_id: &str, sirioctl_path: &str, prompt: &str) -> String {
        format!("{} --prompt {}", self.command(worktree_path, pane_id, sirioctl_path), prompt_argument(prompt))
    }

    fn resume_command(
        &self,
        _worktree_path: &str,
        _pane_id: &str,
        _sirioctl_path: &str,
        session_ref: &str,
    ) -> Option<String> {
        Some(format!("opencode --session {}", shell_quote(session_ref)))
    }

    fn builtin_acp(&self) -> Option<crate::AcpProgram> {
        // Verified live on 2026-08-23 against opencode 1.18.21: piping an
        // ACP `initialize` into `opencode acp` returns
        // `agentInfo: {"name":"OpenCode","version":"1.18.21"}` with
        // sessionCapabilities close/fork/list/resume. The registry agrees —
        // its own `opencode` entry carries `cmd: "./opencode",
        // args: ["acp"]`.
        Some(crate::AcpProgram::new("opencode", &["acp"]))
    }

    fn summarizer_command(&self, prompt: &str) -> Option<String> {
        // `--pure` suppresses the TUI chrome so stdout is only the answer.
        Some(format!("opencode run --pure {}", shell_quote(prompt)))
    }
}

/// The file name of the user-global plugin.
const GLOBAL_PLUGIN_FILE: &str = "sirio-session.js";

/// OpenCode's config directory: `$OPENCODE_CONFIG_DIR`, else `$XDG_CONFIG_HOME/opencode`, else
/// `~/.config/opencode` (empty values ignored) — the lookup `opencode` itself performs
/// (`Global.Path.config`), on Windows included. Its documented user-global plugin directory is
/// `plugins/` (the binary also scans the older singular `plugin/` the worktree-local adapter
/// still writes).
fn opencode_config_dir(home: &Path, environment: &BTreeMap<String, String>) -> PathBuf {
    environment
        .get("OPENCODE_CONFIG_DIR")
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
        .or_else(|| {
            environment
                .get("XDG_CONFIG_HOME")
                .filter(|value| !value.is_empty())
                .map(|xdg| Path::new(xdg).join("opencode"))
        })
        .unwrap_or_else(|| home.join(".config").join("opencode"))
}

/// Removes Sirio's generated user-global plugin (`<config dir>/plugins/sirio-session.js`) and
/// returns its path, or `None` when there is none or the file there is not exactly the generated
/// text, a regular file (not a link) of at most 1 MiB. For a user who moved to OpenCode 2 and
/// keeps the old v1 plugin, which OpenCode 2 reports as "Plugin failed", without pressing Install
/// Hooks again. It does not look at the version memo: the caller decides, and never from
/// `prepare`, which must not touch user-global config.
pub fn remove_generated_global_plugin(
    home: &Path,
    environment: &BTreeMap<String, String>,
) -> Result<Option<PathBuf>, PrepareError> {
    let path = opencode_config_dir(home, environment).join("plugins").join(GLOBAL_PLUGIN_FILE);
    Ok(remove_generated_global(&path)?.then_some(path))
}

/// Removes `path` when it is the file Install Hooks wrote (exactly the generated text, a regular
/// file, not a link). Whether it was removed.
fn remove_generated_global(path: &Path) -> Result<bool, PrepareError> {
    let Ok(meta) = std::fs::symlink_metadata(path) else {
        return Ok(false);
    };
    if !meta.is_file() || meta.len() > 1024 * 1024 {
        return Ok(false);
    }
    let Ok(text) = std::fs::read_to_string(path) else {
        return Ok(false);
    };
    if !is_generated(&text, GLOBAL_PLUGIN_TEMPLATE) {
        return Ok(false);
    }
    std::fs::remove_file(path)?;
    Ok(true)
}

/// What Sirio wrote as the worktree plugin before [`PLUGIN_TEMPLATE`] read the pane from the
/// environment: it names one pane (`__PANE__`), the last tab prepared in that worktree, so it
/// would report every tab's session under that pane. Files of this text are still on users'
/// disks; they are only ever matched to be removed (OpenCode 2 refuses the plugin), never
/// written.
const LEGACY_PANE_PLUGIN_TEMPLATE: &str = "// Generated by Sirio — reports the OpenCode session id for restore.
export const SirioSession = async ({ $ }) => {
  let reported = \"\"
  const sirioctl = __SIRIOCTL__
  const pane = \"__PANE__\"
  return {
    event: async ({ event }) => {
      const id = event?.properties?.info?.id
      if (event?.type === \"session.updated\" && id && id !== reported) {
        reported = id
        await $`${sirioctl} session-ref --session ${pane} --ref ${id}`.quiet().nothrow()
      }
    },
  }
}
";

/// Whether `text` is exactly what Sirio generates from `template`: the template with each
/// placeholder replaced by a value of its strict shape and every other byte (the trailing
/// newline included) unchanged. A header alone is not enough: a user's own OpenCode 2 port that
/// kept Sirio's first line must not be taken for the file to remove. `__SIRIOCTL__` is exactly
/// one JSON string literal on its line, parsed as one (what `json_string_literal` makes of any
/// path; an expression such as `"a" + x() + "b"` is not one); `__PANE__`, which only
/// [`LEGACY_PANE_PLUGIN_TEMPLATE`] has, is `pane-` and digits.
fn is_generated(text: &str, template: &str) -> bool {
    let mut text = text;
    let mut template = template;
    loop {
        let next = [("__SIRIOCTL__", 0), ("__PANE__", 1)]
            .into_iter()
            .filter_map(|(name, kind)| template.find(name).map(|at| (at, name, kind)))
            .min_by_key(|(at, ..)| *at);
        let Some((at, name, kind)) = next else {
            return text == template;
        };
        let Some(rest) = text.strip_prefix(&template[..at]) else {
            return false;
        };
        template = &template[at + name.len()..];
        text = if kind == 0 {
            // The value runs to the end of its line, which the template's next byte ends.
            let line = rest.split('\n').next().unwrap_or_default();
            // serde_json skips JSON whitespace around a literal, but the rule is that every
            // other byte is unchanged, so the line must be the bare literal and nothing else.
            let literal = line.starts_with('"')
                && line.ends_with('"')
                && serde_json::from_str::<String>(line).is_ok()
                && !line.contains('\r');
            if !literal {
                return false;
            }
            &rest[line.len()..]
        } else {
            let Some(digits) = rest.strip_prefix("pane-") else {
                return false;
            };
            let count = digits.bytes().take_while(u8::is_ascii_digit).count();
            if count == 0 {
                return false;
            }
            &digits[count..]
        };
    }
}
